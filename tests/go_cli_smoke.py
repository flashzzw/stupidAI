#!/usr/bin/env python3
"""Exercise the Go backend through a real Codex CLI and a local fake provider.

No real provider credentials or endpoints are used. All Codex control messages
go through `codex app-server proxy`; the mock only serves Codex's requests.
"""
import argparse
import base64
import hashlib
import json
import os
from pathlib import Path
import select
import signal
import shlex
import struct
import subprocess
import tempfile
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer


class Provider(BaseHTTPRequestHandler):
    count = 0
    evidence = None
    requests = []
    stages = {}
    errors = []
    goal_dirs = {}
    block_weather = False
    waiting = threading.Event()
    release = threading.Event()
    lock = threading.Lock()

    def log_message(self, *_args):
        pass

    def do_GET(self):
        body = b'{"object":"list","data":[]}'
        self.send_response(200)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_POST(self):
        import gzip
        import re
        raw = self.rfile.read(int(self.headers.get("Content-Length", 0)))
        if self.headers.get("Content-Encoding") == "gzip":
            raw = gzip.decompress(raw)
        payload = json.loads(raw)
        with Provider.lock:
            Provider.count += 1
            seq = Provider.count
            Provider.requests.append(payload)
        (Provider.evidence / f"request-{seq}.json").write_text(json.dumps(payload, ensure_ascii=False))
        try:
            inputs = payload.get("input", [])
            all_text = json.dumps(inputs, ensure_ascii=False)
            users = [i for i, entry in enumerate(inputs) if entry.get("role") == "user"]
            recent = inputs[users[-1]:] if users else inputs
            prompt = json.dumps(recent, ensure_ascii=False)
            metadata = payload.get("client_metadata", {})
            turn = metadata.get("turn_id", payload.get("prompt_cache_key"))
            stage = Provider.stages.get(turn, 0)
            Provider.stages[turn] = stage + 1
            is_date = "请执行 date -u +%FT%TZ" in prompt
            is_weather = "查询" in prompt and "天气。用法：" in prompt
            is_goal = "Goal 文档" in all_text
            if is_weather and Provider.block_weather:
                Provider.waiting.set()
                Provider.release.wait(25)
            code = None
            if stage == 0 and is_date:
                code = 'text((await tools.exec_command({cmd:"date -u +%FT%TZ",login:false})).output.trim());'
            elif stage == 0 and is_weather:
                # This command is generated by the Go backend and points only at
                # the test's local weather stub. The real Codex executes it.
                message = "".join(c.get("text", "") for c in recent[0].get("content", []))
                command = message.split("用法：", 1)[1].split("。请执行", 1)[0]
                code = 'text((await tools.exec_command(' + json.dumps({"cmd": command, "login": False}) + ')).output.trim());'
            elif stage == 0 and is_goal:
                selected = [(name, path) for name, path in Provider.goal_dirs.items() if str(path) in all_text]
                assert len(selected) == 1, selected
                name, path = selected[0]
                snapshot = re.search(r"Goal 文档 ([^。]+)\。", all_text).group(1)
                command = f"cat {shlex.quote(snapshot)} && printf '%s\\n' {shlex.quote(name + ' completed')} > smoke-result.txt"
                code = ('const r=await tools.exec_command(' + json.dumps({"cmd": command, "workdir": str(path), "login": False}) + ');'
                        'text(r); if(r.exit_code!==0) throw Error("fixture failed");'
                        'text(await tools.update_goal({status:"complete"}));')
            if code:
                item = {"id": f"ctc_{seq}", "type": "custom_tool_call", "call_id": f"call_{seq}",
                        "name": "exec", "namespace": "functions", "input": code, "status": "completed"}
            else:
                outputs = [e for e in recent if e.get("type") in ("custom_tool_call_output", "function_call_output")]
                output = json.dumps(outputs[-1:] or recent, ensure_ascii=False)
                if is_date:
                    dates = re.findall(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ", output)
                    assert dates, output[-2000:]
                    answer = dates[-1]
                elif is_weather:
                    matches = re.findall(r"(?:纽约|洛杉矶|多伦多) fixture: 20 C, clear", output)
                    assert matches, output[-2000:]
                    answer = matches[-1]
                elif is_goal:
                    answer = "测试 Goal 文件已执行，结果已写入 smoke-result.txt。"
                else:
                    answer = "本地人工交互已完成。"
                part = {"type": "output_text", "text": answer, "annotations": []}
                item = {"id": f"msg_{seq}", "type": "message", "role": "assistant",
                        "status": "completed", "phase": "final_answer", "content": [part]}
            response = {"id": f"resp_local_{seq}", "object": "response", "created_at": int(time.time()),
                        "status": "completed", "model": "gpt-6-astra", "output": [item],
                        "usage": {"input_tokens": 32, "output_tokens": 16, "total_tokens": 48}}
            events = [
                ("response.created", {"response": dict(response, status="in_progress", output=[])}),
                ("response.output_item.added", {"output_index": 0, "item": dict(item, status="in_progress")}),
                ("response.output_item.done", {"output_index": 0, "item": item}),
                ("response.completed", {"response": response}),
            ]
            body = "".join(f"event: {kind}\ndata: {json.dumps(dict(event, type=kind, sequence_number=i))}\n\n"
                           for i, (kind, event) in enumerate(events)).encode()
            self.send_response(200)
            self.send_header("Content-Type", "text/event-stream")
        except Exception as error:
            Provider.errors.append(repr(error))
            body = json.dumps({"error": {"message": str(error)}}).encode()
            self.send_response(500)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        try:
            self.wfile.write(body)
        except (BrokenPipeError, ConnectionResetError):
            pass

class Proxy:
    def __init__(self, binary, sock, env):
        self.proc = subprocess.Popen([binary, "app-server", "proxy", "--sock", str(sock)],
                                     env=env, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                     stderr=subprocess.DEVNULL)
        self.buffer = bytearray()
        self.seq = 0
        self.events = []
        key = base64.b64encode(os.urandom(16)).decode()
        self.proc.stdin.write(("GET / HTTP/1.1\r\nHost: localhost\r\nUpgrade: websocket\r\n"
                               "Connection: Upgrade\r\nSec-WebSocket-Key: " + key +
                               "\r\nSec-WebSocket-Version: 13\r\n\r\n").encode())
        self.proc.stdin.flush()
        head = b""
        while not head.endswith(b"\r\n\r\n"):
            head += self.read(1)
            assert len(head) < 16384
        expected = base64.b64encode(hashlib.sha1((key + "258EAFA5-E914-47DA-95CA-C5AB0DC85B11").encode()).digest())
        assert head.startswith(b"HTTP/1.1 101 ") and expected in head
        self.call("initialize", {"clientInfo": {"name": "netcap_local_smoke", "version": "1"},
                                 "capabilities": {"experimentalApi": True}})
        self.send({"method": "initialized"})

    def read(self, size):
        deadline = time.monotonic() + 10
        while len(self.buffer) < size:
            remaining = deadline - time.monotonic()
            if remaining <= 0 or not select.select([self.proc.stdout], [], [], remaining)[0]:
                raise TimeoutError("CLI proxy read timed out")
            part = os.read(self.proc.stdout.fileno(), 65536)
            if not part:
                raise EOFError("CLI proxy closed")
            self.buffer.extend(part)
        out = bytes(self.buffer[:size])
        del self.buffer[:size]
        return out

    def send(self, value):
        data = json.dumps(value).encode()
        mask = os.urandom(4)
        length = len(data)
        if length < 126:
            header = bytes([0x81, 0x80 | length])
        else:
            header = bytes([0x81, 0xfe]) + struct.pack("!H", length)
        self.proc.stdin.write(header + mask + bytes(b ^ mask[i % 4] for i, b in enumerate(data)))
        self.proc.stdin.flush()

    def call(self, method, params):
        self.seq += 1
        self.send({"id": self.seq, "method": method, "params": params})
        while True:
            a, b = self.read(2)
            length = b & 127
            if length == 126:
                length = struct.unpack("!H", self.read(2))[0]
            elif length == 127:
                length = struct.unpack("!Q", self.read(8))[0]
            mask = self.read(4) if b & 128 else None
            data = self.read(length)
            if mask:
                data = bytes(c ^ mask[i % 4] for i, c in enumerate(data))
            if a & 15 != 1:
                continue
            reply = json.loads(data)
            if reply.get("id") == self.seq and "method" not in reply:
                if "error" in reply:
                    raise RuntimeError(f"{method}: {reply['error']}")
                return reply.get("result")
            self.events.append(reply)

    def close(self):
        self.proc.terminate()
        try:
            self.proc.wait(timeout=3)
        except subprocess.TimeoutExpired:
            self.proc.kill()
            self.proc.wait()


def eventually(check, description, timeout=35):
    deadline = time.monotonic() + timeout
    last = None
    while time.monotonic() < deadline:
        try:
            last = check()
            if last:
                return last
        except (FileNotFoundError, subprocess.CalledProcessError):
            pass
        time.sleep(.2)
    raise AssertionError(f"timed out: {description}; last={last!r}")


def stop(proc):
    if proc is None or proc.poll() is not None:
        return
    os.killpg(proc.pid, signal.SIGTERM)
    try:
        proc.wait(timeout=5)
    except subprocess.TimeoutExpired:
        os.killpg(proc.pid, signal.SIGKILL)
        proc.wait()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--netcap", required=True)
    parser.add_argument("--codex", default="codex")
    parser.add_argument("--server-codex", default="codex")
    args = parser.parse_args()
    root = Path(tempfile.mkdtemp(prefix="netcap-go-smoke-"))
    home = root / "codex"
    home.mkdir()
    sock = root / "codex.sock"
    Provider.evidence = root / "requests"
    Provider.evidence.mkdir()
    server = ThreadingHTTPServer(("127.0.0.1", 0), Provider)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    # Deliberately restrictive defaults: managed threads must override them.
    (home / "config.toml").write_text(f'''model = "gpt-6-astra"
model_provider = "local_smoke"
approval_policy = "on-request"
sandbox_mode = "read-only"
[model_providers.local_smoke]
name = "Local smoke fixture"
base_url = "http://127.0.0.1:{server.server_port}/v1"
wire_api = "responses"
requires_openai_auth = false
supports_websockets = false
request_max_retries = 0
stream_max_retries = 0
stream_idle_timeout_ms = 30000
[features]
apps = false
plugins = false
shell_snapshot = false
''')
    env = {k: v for k, v in os.environ.items() if k in ("PATH", "HOME", "USER", "LANG", "TERM", "SHELL")}
    env["CODEX_HOME"] = str(home)
    weather = root / "weather.py"
    weather.write_text('''import json, sys
if sys.argv[1] == "--list-cities":
    print(json.dumps(["纽约", "洛杉矶", "多伦多"]))
else:
    print(sys.argv[1] + " fixture: 20 C, clear")
''')
    cfg = root / "netcap.json"
    config = {"codex_home": str(home), "codex_bin": args.codex,
              "codex_socket": str(sock), "state_dir": str(root / "state"),
              "model": "gpt-6-astra", "provider": "local_smoke", "weather_script": str(weather),
              "poll_seconds": 1, "weather_interval_seconds": 2,
              "weather_timeout_seconds": 20, "probe_timeout_seconds": 20,
              "auto_start_daemon": False}
    cfg.write_text(json.dumps(config))
    server_log = (root / "codex.log").open("w")
    guard_log = (root / "netcap.log").open("w")
    codex_proc = guard_proc = proxy = None

    def cli(*argv):
        result = subprocess.run([args.netcap, "--config", str(cfg), *argv], env=env,
                                text=True, capture_output=True, timeout=20, check=True)
        return json.loads(result.stdout)

    def snapshot():
        return cli("status")["state"]

    def spawn_guard():
        return subprocess.Popen([args.netcap, "--config", str(cfg), "run"], cwd=root, env=env,
                                stdout=guard_log, stderr=guard_log, start_new_session=True)

    def complete(tid):
        turns = proxy.call("thread/read", {"threadId": tid, "includeTurns": True})["thread"]["turns"]
        return bool(turns) and turns[-1]["status"] == "completed"

    def human_turn(tid):
        proxy.call("turn/start", {"threadId": tid, "input": [{"type": "text", "text": "本地测试：人工现在接管交互。"}]})
        eventually(lambda: complete(tid), "human fixture turn completes")
        eventually(lambda: not snapshot()["running"], "human activity persistently pauses automation")
        assert snapshot()["pause_reason"] == "human"

    def pause_clean():
        cli("pause")
        eventually(lambda: not snapshot().get("operation"), "weather cleanup")
        eventually(lambda: snapshot()["probe"]["status"] != "running", "probe cleanup")

    try:
        codex_proc = subprocess.Popen([args.server_codex, "app-server", "--listen", "unix://" + str(sock)],
                                      cwd=root, env=env, stdout=server_log, stderr=server_log, start_new_session=True)
        eventually(lambda: sock.exists(), "isolated Codex server socket", timeout=10)
        proxy = Proxy(args.codex, sock, env)
        guard_proc = spawn_guard()
        eventually(lambda: snapshot()["weather"].get("last_city") == "洛杉矶", "automatic date probe then two cities", timeout=45)
        state = snapshot()
        assert state["probe"]["status"] == "succeeded", state
        tid = state["weather"]["thread_id"]
        completed = [o for o in state["operations"] if o["status"] == "succeeded"]
        assert [o["city"] for o in completed[:2]] == ["纽约", "洛杉矶"], completed
        assert all(o["thread_id"] == tid for o in completed)
        assert "fixture" in state["weather"]["last_output"]
        print("PASS: real ephemeral date execution -> persistent weather commands in city order", flush=True)

        # Resume exactly the weather ID through another CLI proxy, as a human UI does.
        proxy.call("thread/resume", {"threadId": tid, "excludeTurns": True})
        human_turn(tid)
        assert snapshot()["weather"]["human_owned"] is True
        cli("resume")
        def new_weather():
            s = snapshot()
            return s["weather"].get("thread_id") not in (None, "", tid) and bool(s["weather"].get("last_city"))
        eventually(new_weather, "explicit resume creates a new weather session", timeout=45)
        new_tid = snapshot()["weather"]["thread_id"]
        print("PASS: resume weather ID hands over; explicit automation resume uses a new saved session", flush=True)

        human = proxy.call("thread/start", {"cwd": str(root), "sandbox": "danger-full-access", "approvalPolicy": "never"})["thread"]
        human_turn(human["id"])
        assert snapshot()["weather"]["thread_id"] == new_tid
        pause_clean()
        stop(guard_proc)
        guard_proc = spawn_guard()
        eventually(lambda: cli("status")["connection"] == "ready", "restart connection")
        assert snapshot()["running"] is False
        assert snapshot()["weather"]["thread_id"] == new_tid
        print("PASS: new human conversation pauses; restart preserves pause and saved weather ID", flush=True)

        # Pause an in-flight pure weather turn through the real queue/interrupt APIs.
        Provider.block_weather = True
        Provider.release.clear()
        Provider.waiting.clear()
        cli("resume")
        eventually(Provider.waiting.is_set, "in-flight weather request", timeout=45)
        pause_clean()
        assert any(o["status"] == "interrupted" for o in snapshot()["operations"])
        Provider.block_weather = False
        Provider.release.set()
        stop(guard_proc)
        print("PASS: pause interrupts only the owned weather turn", flush=True)

        # New state directory isolates two native Goals from the weather scenario.
        goals = []
        for name in ("first", "second"):
            cwd = root / name
            cwd.mkdir()
            source = root / f"{name}.md"
            source.write_text(f"在当前目录写入 smoke-result.txt，内容为 {name} completed 和换行；确认后完成原生 Goal。")
            Provider.goal_dirs[name] = cwd
            goals.append({"id": name, "file": str(source), "cwd": str(cwd)})
        config.update(state_dir=str(root / "goal-state"), goals=goals)
        cfg.write_text(json.dumps(config))
        guard_proc = spawn_guard()
        eventually(lambda: len(cli("goals")) == 2 and all(g["status"] == "complete" for g in cli("goals")),
                   "two native Goals executed and completed", timeout=55)
        jobs = cli("goals")
        assert jobs[0]["thread_id"] != jobs[1]["thread_id"]
        for job in jobs:
            native = proxy.call("thread/goal/get", {"threadId": job["thread_id"]})["goal"]
            assert native["status"] == "complete", native
            thread = proxy.call("thread/read", {"threadId": job["thread_id"]})["thread"]
            assert thread["cwd"] == str(Provider.goal_dirs[job["id"]]), thread
            assert (Provider.goal_dirs[job["id"]] / "smoke-result.txt").read_text() == job["id"] + " completed\n"
        events = cli("events")
        order = [(e["kind"], e["message"].split()[0]) for e in events if e["kind"] in ("goal_created", "goal_complete")]
        assert order == [("goal_created", "first"), ("goal_complete", "first"), ("goal_created", "second"), ("goal_complete", "second")], order
        eventually(lambda: bool(snapshot()["weather"].get("last_city")), "weather follows exhausted native Goal queue")
        pause_clean()
        stop(guard_proc)
        guard_proc = spawn_guard()
        eventually(lambda: cli("status")["connection"] == "ready", "completed Goals restart")
        assert snapshot()["running"] is False
        assert all(g["status"] == "complete" for g in cli("goals"))
        print("PASS: native Goal tools complete real files in separate cwd/sessions, then weather; restart preserves completion", flush=True)

        # Check the effective permissions sent by Codex, not just our RPC arguments.
        probe_ids = set()
        for request in Provider.requests:
            meta = json.loads(request["client_metadata"]["x-codex-turn-metadata"])
            assert meta["sandbox_mode"] == "danger-full-access", meta
            assert meta["sandbox"] == "none", meta
            body = json.dumps(request.get("input", []), ensure_ascii=False)
            assert "Approval policy is currently never" in body
            if "请执行 date -u +%FT%TZ" in body:
                probe_ids.add(request["client_metadata"]["thread_id"])
        rollouts = [str(p) for p in home.glob("sessions/**/*.jsonl")]
        assert probe_ids and all(not any(tid in path for path in rollouts) for tid in probe_ids)
        assert any(tid in path for path in rollouts), "weather session did not persist"
        assert not Provider.errors, Provider.errors
        print("PASS: all requests use no approval/no sandbox; probe sessions have no rollouts", flush=True)
        print(f"Local model requests: {Provider.count}; evidence directory: {root}", flush=True)
    except Exception:
        print(f"Smoke failed; evidence directory: {root}; provider errors: {Provider.errors}", flush=True)
        print((root / "netcap.log").read_text()[-12000:], flush=True)
        raise
    finally:
        Provider.release.set()
        stop(guard_proc)
        if proxy:
            proxy.close()
        stop(codex_proc)
        server.shutdown()
        server.server_close()
        guard_log.close()
        server_log.close()


if __name__ == "__main__":
    main()
