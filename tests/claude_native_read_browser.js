async page => {
  const work = __WORK__, info = __INFO__;
  const checks = {}, requests = [], errors = [];
  const check = (name, ok) => { checks[name] = !!ok; if (!ok) throw Error(name); };
  await page.unrouteAll({ behavior: 'ignoreErrors' });
  await page.context().clearCookies();
  await page.context().addCookies([{ name: 'netcap_session', value: info.token, url: info.url + '/api', httpOnly: true, sameSite: 'Strict' }]);
  await page.addInitScript(() => sessionStorage.clear());
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => {
    const path = r.url().replace(/^https?:\/\/[^/]+/, '').split('?')[0];
    if (path.startsWith('/api/') && path !== '/api/login') requests.push({ path, method: r.method(), body: r.postData() });
  });
  page.setDefaultTimeout(10000);
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.goto(info.url);
  await page.getByRole('button', { name: '发现原生会话', exact: true }).click();
  await page.getByRole('button', { name: '查询原生记录', exact: true }).click();
  await page.getByText(info.native_id, { exact: true }).first().waitFor();
  check('native_profile_with_helper_discoverable', await page.getByText(info.native_id, { exact: true }).count() > 0);
  await page.getByRole('textbox', { name: '原生会话 ID', exact: true }).fill(info.native_id);
  await page.getByRole('button', { name: '按 ID 只读预览', exact: true }).click();
  const preview = page.locator('section[aria-label="原生记录预览"]');
  await preview.waitFor();
  check('preview_original_identity', (await preview.innerText()).includes(info.native_id));
  check('preview_does_not_grant_control', (await preview.innerText()).includes('不授予发送或恢复权限'));
  await preview.getByRole('button', { name: '读取原生历史', exact: true }).click();
  const history = page.locator('section[aria-label="原生历史只读查看"]');
  await history.waitFor();
  await history.locator('.native-history-entry').first().waitFor();
  check('original_history_visible', (await history.innerText()).includes('NETCAP_WORKER_RETRY'));
  await page.getByRole('button', { name: '关闭历史', exact: true }).click();
  await preview.getByRole('button', { name: '登记为只读原生会话', exact: true }).click();
  await page.locator('.conversation-header h1').waitFor();
  check('bound_source_labeled_readonly', (await page.locator('.conversation-header').innerText()).includes('外部原生只读绑定'));
  check('bound_source_has_no_composer', await page.locator('#message').count() === 0);
  const snapResponse = await page.request.get(info.url + '/api/snapshot');
  check('real_handler_snapshot_succeeds', snapResponse.status() === 200);
  const snap = await snapResponse.json();
  check('one_readonly_binding', snap.sessions.length === 1 && snap.sessions[0].scope.native_id === info.native_id && snap.sessions[0].control_mode === 'native_readonly');
  check('no_native_operations_created', snap.operations.length === 0);
  await page.screenshot({ path: work + '/native-read-1440.png', fullPage: true });
  await page.getByRole('button', { name: '执行配置', exact: true }).click();
  const use = page.getByRole('button', { name: '使用此配置', exact: true });
  await use.waitFor();
  check('conflicting_profile_create_stays_disabled', await use.isDisabled());
  await page.setViewportSize({ width: 390, height: 844 });
  check('narrow_view_no_overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: work + '/native-read-390.png', fullPage: true });
  check('no_execution_commands_sent', !requests.some(r => r.path === '/api/commands'));
  check('no_page_errors', errors.length === 0);
  const result = { passed: Object.values(checks).every(Boolean), checks, requests, errors, scope: 'live production Handler and browser; native worker is stopped; no replayed HTTP or model calls' };
  return result;
}
